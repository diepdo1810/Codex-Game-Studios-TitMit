import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync,writeFileSync,copyFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=process.cwd(),fixture=mkdtempSync(path.join(tmpdir(),'cgs-native-generator-'));
const registry=JSON.parse(readFileSync('docs/codex/generation-manifest.json'));
const migration=JSON.parse(readFileSync('docs/codex/migration-manifest.json'));
const files=new Set(['docs/codex/upstream-inventory.json','docs/codex/migration-manifest.json','docs/codex/generation-manifest.json','docs/codex/active-baseline.json','.codex/model-policy.json','.agents/rules/index.json','studio-tests/catalog.yaml',...registry.entries.map(e=>e.target),...migration.entries.flatMap(e=>[...(e.target&&(e.target_sha256||['PORTED','EQUIVALENT'].includes(e.status))?[e.target]:[]),...(e.related_targets||[]).map(t=>t.target)])]);
for(const e of migration.retired_manual_mappings||[])files.add(e.target);
files.add('.agents/framework-version');
files.add('docs/codex/engine-skills.md');
for(const m of readFileSync('studio-tests/catalog.yaml','utf8').matchAll(/^    spec: (\S+)/gm))files.add(m[1]);
for(const p of files){mkdirSync(path.dirname(path.join(fixture,p)),{recursive:true});copyFileSync(path.join(root,p),path.join(fixture,p))}
const script=path.join(root,'scripts/codex/generate.mjs');
const run=(...args)=>spawnSync(process.execPath,[script,'--root',fixture,...args],{encoding:'utf8'});
const target='.agents/skills/help/SKILL.md',other=registry.entries.find(e=>e.target!==target&&e.target.startsWith('.agents/skills/')&&e.target.endsWith('/SKILL.md')).target;
const file=path.join(fixture,target),otherFile=path.join(fixture,other),original=readFileSync(file),otherOriginal=readFileSync(otherFile);
const manifest=path.join(fixture,'docs/codex/generation-manifest.json'),matrix=path.join(fixture,'docs/codex/migration-manifest.json');
assert.equal(run('--check').status,0);
writeFileSync(file,Buffer.concat([original,Buffer.from('\nNative fixture edit.\n')]));
const drift=run('--check');assert.notEqual(drift.status,0);assert.match(drift.stderr,/Target drift/);
const unknown=run('--record-native','--targets','.agents/skills/unknown/SKILL.md');assert.notEqual(unknown.status,0);assert.match(unknown.stderr,/Unregistered target/);
writeFileSync(otherFile,Buffer.concat([otherOriginal,Buffer.from('\nUnselected edit.\n')]));
const unselected=run('--record-native','--targets',target);assert.notEqual(unselected.status,0);assert.match(unselected.stderr,/Unselected target drift/);
assert.equal(readFileSync(file,'utf8'),original.toString()+'\nNative fixture edit.\n');
writeFileSync(otherFile,otherOriginal);
const beforeManifest=readFileSync(manifest),beforeMatrix=readFileSync(matrix);
writeFileSync(file,'invalid frontmatter\n');
const invalid=run('--record-native','--targets',target);assert.notEqual(invalid.status,0);assert.match(invalid.stderr,/Native validation failed/);
assert.deepEqual(readFileSync(manifest),beforeManifest);assert.deepEqual(readFileSync(matrix),beforeMatrix);
writeFileSync(file,Buffer.concat([original,Buffer.from('\nNative fixture edit.\n')]));
const accepted=run('--record-native','--targets',target);assert.equal(accepted.status,0,accepted.stderr);
assert.equal(run('--check').status,0);
console.log('PASS offline generator detects drift, refuses unselected/unregistered targets, restores invalid metadata and records reviewed native target');
